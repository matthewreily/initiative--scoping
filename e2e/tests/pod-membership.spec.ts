import { test, expect } from '@playwright/test';
import { addPhase, createInitiative, isoDate, uniqueName } from './helpers';

test('membership split previews effective allocation and opt-in resync preserves manual hours', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1024, height: 900 });
  const id = await createInitiative(page, uniqueName('Pod split'));
  await addPhase(page, 'Implementation and verification', isoDate(0), isoDate(20));
  const name = uniqueName('Membership split delivery pod');
  await page.goto('/Admin/Pods/Create');
  await page.locator('#Name').fill(name);
  await page.locator('#BusinessUnitId').selectOption({ index: 1 });
  const member = page.locator('input[name="PersonIds"]').first();
  const personId = await member.inputValue();
  await member.check();
  await page.locator(`#membership-${personId}`).fill('40');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  const podEdit = await page.locator('.card', { hasText: name }).getByRole('link', { name: 'Edit' }).getAttribute('href');
  await page.goto(`/Initiatives/DevelopmentPods/${id}`);
  await page.locator('#PodId').selectOption({ label: name });
  const podId = await page.locator('#PodId').inputValue();
  await page.locator('#AllocationPercent').fill('50');
  await expect(page.locator(`[data-pod-members="${podId}"] output`)).toHaveText('20');
  await page.locator('input[name="PhaseIds"]').check();
  await page.getByRole('button', { name: 'Assign pod', exact: true }).click();
  const edit = await page.locator('#allocations-table').getByRole('link', { name: 'Edit', exact: true }).getAttribute('href');
  const preview = `/Initiatives/ResyncPod/${id}?podId=${podId}`;
  async function changeMembership(percent: string) {
    await page.goto(podEdit!);
    await page.locator(`#membership-${personId}`).fill(percent);
    await page.getByRole('button', { name: 'Save', exact: true }).click();
    await page.goto(preview);
  }
  await changeMembership('60');
  const update = page.locator('input[name="updateAllocationIds"]');
  await expect(update).toBeChecked();
  await expect(page.getByText(/20% → 30%/)).toBeVisible();
  const fit = await page.locator('main').evaluate(el => ({ clientWidth: el.clientWidth, scrollWidth: el.scrollWidth }));
  console.log('POD_RESYNC_FIT 1024', JSON.stringify(fit));
  expect(fit.scrollWidth).toBeLessThanOrEqual(fit.clientWidth);
  await page.screenshot({ path: testInfo.outputPath('pod-resync-1024.png'), fullPage: true });
  await page.getByRole('button', { name: 'Confirm re-sync' }).click();
  await page.goto(preview);
  await expect(page.getByRole('heading', { name: 'Seats to update (0)', exact: true })).toBeVisible();
  await page.goto(edit!);
  await page.locator('#EstimatedHours').fill('23');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await changeMembership('80');
  await expect(update).not.toBeChecked();
  await expect(page.locator('.badge', { hasText: 'hand-edited' })).toBeVisible();
  await page.getByRole('button', { name: 'Confirm re-sync' }).click();
  await page.goto(edit!);
  await expect(page.locator('#EstimatedHours')).toHaveValue(/^23(?:\.0+)?$/);
  await page.goto(preview);
  await update.check();
  await page.getByRole('button', { name: 'Confirm re-sync' }).click();
  await page.goto(preview);
  await expect(page.getByRole('heading', { name: 'Seats to update (0)', exact: true })).toBeVisible();
});
